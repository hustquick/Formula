const assert=require('node:assert/strict'),fs=require('node:fs');
const {chromium}=require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES?process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES+'/playwright':'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});const page=await browser.newPage();
 await page.setContent('<button>图片识别</button><button disabled>文档识别</button>');
 await page.evaluate(()=>{
  window.calls=[];window.imports=[];window.forwarded=[];
  window.FormulaImport=(...x)=>imports.push(x);window.FormulaNativeReply=(...x)=>forwarded.push(x);
  window.webkit={messageHandlers:{mathforge:{postMessage:m=>{calls.push(m);if(m.action==='ocrStatus')setTimeout(()=>FormulaNativeReply(m.id,{installed:true,documentInstalled:true}),0);}}}};
 });
 await page.addScriptTag({content:fs.readFileSync('web/ocr.js','utf8')});
 await page.getByRole('button',{name:'文档识别',exact:true}).click();
 await page.locator('[data-doc-recognize]').click();
 await page.evaluate(()=>FormulaOCRProgress(calls.at(-1).id,{message:'正在识别第 2 页',total:3,completed:1}));
 assert.equal(await page.locator('[data-doc-status]').textContent(),'正在识别第 2 页');
 assert.equal(await page.locator('[data-doc-progress]').evaluate(x=>x.value),1);
 await page.evaluate(()=>FormulaNativeReply(calls.at(-1).id,{sourceName:'sample.docx',markdown:'Body\n$$x^2$$',warnings:['测试提示'],pages:[{source:'Word 文档',items:[{type:'embedding',text:'x^2',source:'Word 段落 1'},{type:'isolated',text:'a+b=c',source:'Word 图片 1'}]}]}));
 await page.waitForFunction(()=>!document.querySelector('[data-doc-results]').hidden);
 assert.equal(await page.locator('[data-doc-formulas] input').count(),2);
 assert.equal(await page.locator('[data-doc-preview]').inputValue(),'Body\n$$x^2$$');
 assert.equal(await page.locator('[data-doc-warnings]').textContent(),'测试提示');
 await page.locator('[data-doc-copy]').click();
 assert.equal(await page.evaluate(()=>calls.at(-1).text),'Body\n$$x^2$$');
 await page.locator('[data-doc-export]').click();
 assert.equal(await page.evaluate(()=>calls.at(-1).name),'sample-识别结果.md');
 assert.equal(await page.evaluate(()=>atob(calls.at(-1).base64)),'Body\n$$x^2$$');
 await page.evaluate(()=>FormulaNativeReply(calls.at(-1).id,{saved:true}));
 await page.locator('[data-doc-formulas] input').first().check();
 await page.locator('[data-doc-formulas] input').last().check();
 await page.locator('[data-doc-import]').click();
 assert.deepEqual(await page.evaluate(()=>imports),[['\\begin{aligned}\n& x^2 \\\\\n& a+b=c\n\\end{aligned}','tex']]);
 await page.getByRole('button',{name:'文档识别',exact:true}).click();
 await page.locator('[data-doc-last]').fill('25');
 const before=await page.evaluate(()=>calls.length);
 await page.locator('[data-doc-recognize]').click();
 assert.equal(await page.evaluate(()=>calls.length),before);
 await page.locator('[data-doc-last]').fill('');
 await page.locator('[data-doc-recognize]').click();
 await page.evaluate(()=>FormulaNativeReply(calls.at(-1).id,{cancelled:true}));
 await page.waitForFunction(()=>document.querySelector('[data-doc-status]').textContent.includes('已取消'));
 assert.equal(await page.locator('[data-doc-preview]').inputValue(),'Body\n$$x^2$$');
 await page.locator('[data-doc-recognize]').click();
 await page.evaluate(()=>FormulaNativeReply(calls.at(-1).id,{error:'PDF 已加密',log:'Password required'}));
 await page.waitForFunction(()=>document.querySelector('[data-doc-status]').textContent==='PDF 已加密');
 assert.equal(await page.locator('[data-doc-log]').textContent(),'Password required');
 await page.evaluate(()=>FormulaNativeReply('other',{ok:true}));
 assert.deepEqual(await page.evaluate(()=>forwarded),[['other',{ok:true}]]);
 await browser.close();console.log('Document UI: progress, preview, warnings, copy/export, selected import, PDF ranges, cancellation and error logs OK');
})().catch(e=>{console.error(e);process.exit(1)});
